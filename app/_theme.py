def _make_particles(n: int = 40, seed: int = 7) -> str:
    """Generate N floating particle divs with deterministic random positions/timings.
    Pure HTML + inline CSS — no JavaScript required."""
    rng = _random.Random(seed)
    parts = ['<div id="arch-particles">']
    for _ in range(n):
        x       = rng.uniform(0, 100)          # left position (vw)
        size    = rng.uniform(1.2, 3.2)        # diameter (px)
        dur     = rng.uniform(10, 26)          # float duration (s)
        delay   = rng.uniform(0, 22)           # start offset (s, negative = mid-anim)
        opacity = rng.uniform(0.10, 0.42)
        color   = (
            f"rgba(212,168,67,{opacity:.2f})"
            if rng.random() > 0.38
            else f"rgba(74,158,191,{opacity:.2f})"
        )
        parts.append(
            f'<div class="arch-p" style="'
            f'left:{x:.1f}vw;'
            f'width:{size:.1f}px;height:{size:.1f}px;'
            f'background:{color};'
            f'animation-duration:{dur:.1f}s;'
            f'animation-delay:-{delay:.1f}s;'
            f'"></div>'
        )
    parts.append('</div>')
    return ''.join(parts)


